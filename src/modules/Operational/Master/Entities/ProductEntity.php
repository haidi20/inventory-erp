    private static function formatTimestamp(mixed $value): ?string
    {
        if (empty($value)) {
            return null;
        }

        if ($value instanceof \DateTimeInterface) {
            return $value->format('Y-m-d H:i:s');
        }

        return date('Y-m-d H:i:s', (int) $value);
    }

