            item_name_alt: $model->item_name_alt,
            group_uuid: $model->item_group_lookup_uuid,
            type_uuid: $model->item_type_lookup_uuid,
            brand_uuid: $model->brand_lookup_uuid,
            origin_uuid: $model->origin_lookup_uuid,
            grade_uuid: $model->grade_lookup_uuid,
            opening_cost: (float) ($model->opening_cost ?? 0),
            coa_sales_uuid: $model->coa_sales_uuid,
            coa_inventory_uuid: $model->coa_inventory_uuid,
            coa_sales_discount_uuid: $model->coa_sales_discount_uuid,
            coa_hpp_uuid: $model->coa_hpp_uuid,
            coa_sales_return_uuid: $model->coa_sales_return_uuid,
            coa_purchase_return_uuid: $model->coa_purchase_return_uuid,
            coa_suspend_uuid: $model->coa_suspend_uuid,
            group_name: $model->groupLookup?->display_name,
            type_name: $model->typeLookup?->display_name,
            brand_name: $model->brandLookup?->display_name ?? $model->brand,
            origin_name: $model->originLookup?->display_name ?? $model->origin,
            grade_name: $model->gradeLookup?->display_name ?? $model->grade,
            created_by_name: $model->createdByUser?->name,
            updated_by_name: $model->updatedByUser?->name,
            created_at: self::formatTimestamp($model->created_at),
            updated_at: self::formatTimestamp($model->updated_at),
            stock: (float) ($model->stock ?? 0.0),
            units: $model->relationLoaded('units') ? $model->units->map(fn ($row) => [
                'uuid' => $row->uuid,
                'unit_uuid' => $row->unit_uuid,
                'conversion_ratio' => (float) ($row->conversion_ratio ?? 1),
                'note' => $row->note,
                'is_default' => (bool) ($row->is_base ?? false),
                'is_active' => (bool) (($row->deleted_at ?? 0) === 0),
            ])->values()->all() : null,
            prices: $model->relationLoaded('prices') ? $model->prices->map(fn ($row) => [
                'uuid' => $row->uuid,
                'price_level_uuid' => $row->price_level_uuid,
                'price' => (float) ($row->price ?? 0),
                'is_active' => (bool) ($row->is_active ?? true),
            ])->values()->all() : null,
            opening_balances: $model->relationLoaded('openingBalances') ? $model->openingBalances->map(fn ($row) => [
                'uuid' => $row->uuid,
                'location_uuid' => $row->location_uuid,
                'opening_qty' => (float) ($row->opening_qty ?? 0),
                'period' => $row->period_month,
            ])->values()->all() : null,
            discounts: $model->relationLoaded('discountRules') ? $model->discountRules->map(fn ($row) => [
                'uuid' => $row->uuid,
                'quantity' => (float) ($row->min_qty ?? 0),
